#!/usr/bin/env node
// Generates the rules table in spec/rules/README.md from rule-file frontmatter
// (spec/rules/generated-registries.md). The table between the markers is
// GENERATED — hand-edits there are overwritten. Prose outside the markers is
// hand-written and untouched.
//
//   node scripts/generate-rules-index.mjs          # rewrite the table in place
//   node scripts/generate-rules-index.mjs --check  # exit 1 if table is stale (CI)

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const RULES_DIR = join(dirname(fileURLToPath(import.meta.url)), '..', 'spec', 'rules')
const README = join(RULES_DIR, 'README.md')
const BEGIN = '<!-- rules-table:begin (generated by scripts/generate-rules-index.mjs — do not hand-edit) -->'
const END = '<!-- rules-table:end -->'
const FIELDS = ['id', 'scope', 'principle', 'enforcement', 'gate', 'guards']

function parseFrontmatter(file, text) {
  const match = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!match) throw new Error(`${file}: missing frontmatter`)
  const meta = {}
  for (const line of match[1].split('\n')) {
    const idx = line.indexOf(':')
    if (idx === -1) continue
    meta[line.slice(0, idx).trim()] = line.slice(idx + 1).trim()
  }
  for (const field of FIELDS) {
    if (!meta[field]) throw new Error(`${file}: frontmatter missing "${field}"`)
  }
  return meta
}

function code(value) {
  return value === '—' || value === '' ? '—' : `\`${value}\``
}

const files = readdirSync(RULES_DIR)
  .filter((f) => f.endsWith('.md') && f !== 'README.md')
  .sort()

const rules = files.map((f) => ({
  file: f,
  ...parseFrontmatter(f, readFileSync(join(RULES_DIR, f), 'utf8')),
}))

// meta (layer 0) rows first, then alphabetical by id — deterministic, not curated.
rules.sort((a, b) =>
  (a.scope === 'meta' ? 0 : 1) - (b.scope === 'meta' ? 0 : 1) || a.id.localeCompare(b.id),
)

const header = '| Rule | Scope | Principle | Guards (typed model) | Enforcement | Gate |\n|---|---|---|---|---|---|'
const rows = rules.map(
  (r) =>
    `| [${r.id}](${r.file}) | ${r.scope} | ${r.principle} | ${r.guards} | ${r.enforcement} | ${code(r.gate)} |`,
)
const table = [BEGIN, header, ...rows, END].join('\n')

const readme = readFileSync(README, 'utf8')
const beginIdx = readme.indexOf(BEGIN)
const endIdx = readme.indexOf(END)
if (beginIdx === -1 || endIdx === -1) {
  console.error(`${README}: markers not found — add ${BEGIN} / ${END} around the table`)
  process.exit(1)
}
const updated = readme.slice(0, beginIdx) + table + readme.slice(endIdx + END.length)

if (process.argv.includes('--check')) {
  if (updated !== readme) {
    console.error('spec/rules/README.md table is stale — run: node scripts/generate-rules-index.mjs')
    process.exit(1)
  }
  console.log(`rules index up to date (${rules.length} rules)`)
} else {
  writeFileSync(README, updated)
  console.log(`rules index written (${rules.length} rules)`)
}
